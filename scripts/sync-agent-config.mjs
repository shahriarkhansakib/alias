#!/usr/bin/env node
/**
 * Generates tool-specific agent files from the canonical, tool-neutral sources.
 *
 * Sources (edit these):
 *   AGENTS.md files anywhere in the repo   -> read natively by most agents
 *   .agents/claude-code.md                 -> Claude-Code-only notes appended to the root CLAUDE.md
 *   .agents/rules/*.md                     -> read natively by Antigravity
 *   .agents/skills/<name>/                 -> read natively by Antigravity (Agent Skills standard)
 *
 * Generated (never edit by hand):
 *   CLAUDE.md next to every AGENTS.md      -> `@AGENTS.md` import for Claude Code
 *   .claude/rules/*.md                     -> Claude Code rules (`paths:` frontmatter)
 *   .claude/skills/<name>/                 -> copy of each skill for Claude Code
 *   .claude/.generated-manifest.json       -> list of the files above; only these are ever deleted
 *
 * Usage:
 *   node scripts/sync-agent-config.mjs          write the generated files
 *   node scripts/sync-agent-config.mjs --check  exit 1 if generated files are out of date
 */
import { execFileSync } from 'node:child_process';
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const ROOT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const CHECK = process.argv.includes('--check');
const MARKER = 'Generated by scripts/sync-agent-config.mjs';
const CLAUDE_EXTRA_SRC = '.agents/claude-code.md';
const RULES_SRC = '.agents/rules';
const SKILLS_SRC = '.agents/skills';
const CLAUDE_RULES = '.claude/rules';
const CLAUDE_SKILLS = '.claude/skills';
const MANIFEST = '.claude/.generated-manifest.json';
/** Files with these extensions are compared and written as text with LF line endings. */
const TEXT_EXTENSIONS = new Set(['.md', '.markdown', '.txt']);

/**
 * repo-relative path -> expected content.
 * @type {Map<string, { text: string } | { bytes: Buffer }>}
 */
const expected = new Map();
const problems = [];

function abs(rel) {
  return path.join(ROOT, rel);
}

function exists(rel) {
  return fs.existsSync(abs(rel));
}

function isText(rel) {
  return TEXT_EXTENSIONS.has(path.posix.extname(rel).toLowerCase());
}

/** Strips a UTF-8 byte-order mark and converts CRLF / CR line endings to LF. */
function normalizeText(text) {
  return text.replace(/^\uFEFF/, '').replace(/\r\n?/g, '\n');
}

function readText(rel) {
  return normalizeText(fs.readFileSync(abs(rel), 'utf8'));
}

function gitListFiles(names) {
  const pathspecs = names.flatMap((name) => [name, `**/${name}`]);
  const out = execFileSync(
    'git',
    ['ls-files', '--cached', '--others', '--exclude-standard', '--', ...pathspecs],
    { cwd: ROOT, encoding: 'utf8' },
  );
  return [
    ...new Set(
      out
        .split('\n')
        .map((l) => l.trim())
        // `git ls-files --cached` still lists files deleted from disk but not yet staged.
        .filter((l) => l && exists(l)),
    ),
  ].sort();
}

function unquote(value) {
  const match = value.match(/^"(.*)"$/) ?? value.match(/^'(.*)'$/);
  return match ? match[1] : value;
}

/**
 * Parses the small YAML subset used in rule frontmatter:
 *   key: value            key: "quoted value"
 *   key: [a, "b"]         key:
 *                           - a
 *                           - "b"
 */
function parseFrontmatter(text, file) {
  const match = text.match(/^---\n([\s\S]*?)\n---(?:\n|$)([\s\S]*)$/);
  if (!match) throw new Error(`${file}: missing YAML frontmatter (the file must start with ---)`);
  const data = {};
  let listKey = null;
  for (const line of match[1].split('\n')) {
    if (!line.trim() || line.trim().startsWith('#')) continue;
    const item = line.match(/^\s*-\s+(.*)$/);
    if (item && listKey) {
      data[listKey].push(unquote(item[1].trim()));
      continue;
    }
    const kv = line.match(/^([A-Za-z_][\w-]*):\s*(.*)$/);
    if (!kv) throw new Error(`${file}: cannot parse frontmatter line: ${JSON.stringify(line)}`);
    const [, key, rawValue] = kv;
    const value = rawValue.trim();
    if (value === '') {
      data[key] = [];
      listKey = key;
    } else if (value.startsWith('[') && value.endsWith(']')) {
      data[key] = value
        .slice(1, -1)
        .split(',')
        .map((v) => unquote(v.trim()))
        .filter(Boolean);
      listKey = null;
    } else {
      data[key] = unquote(value);
      listKey = null;
    }
  }
  return { data, body: match[2] };
}

function parseGlobs(value, file) {
  const globs = Array.isArray(value)
    ? value.map((g) => g.trim()).filter(Boolean)
    : typeof value === 'string'
      ? value
          .split(',')
          .map((g) => g.trim())
          .filter(Boolean)
      : [];
  if (globs.length === 0) {
    throw new Error(
      `${file}: \`trigger: glob\` needs \`globs\`, either a comma-separated string ` +
        '(globs: "apps/web/**, packages/ui/**") or a YAML list (globs:\\n  - "apps/web/**"). ' +
        'Use the YAML list form for patterns that contain commas, such as {a,b}.',
    );
  }
  return globs;
}

function walk(relDir) {
  if (!exists(relDir)) return [];
  return fs.readdirSync(abs(relDir), { withFileTypes: true }).flatMap((entry) => {
    const rel = `${relDir}/${entry.name}`;
    return entry.isDirectory() ? walk(rel) : [rel];
  });
}

// 1. CLAUDE.md next to every AGENTS.md
const claudeExtra = exists(CLAUDE_EXTRA_SRC) ? readText(CLAUDE_EXTRA_SRC) : '';
for (const agentsFile of gitListFiles(['AGENTS.md']).filter((f) => !f.startsWith('.agents/'))) {
  const dir = path.posix.dirname(agentsFile);
  const isRoot = dir === '.';
  const sources = isRoot && claudeExtra ? `AGENTS.md and ${CLAUDE_EXTRA_SRC}` : 'AGENTS.md';
  let text = `<!-- ${MARKER} from ${sources}. Do not edit; edit the source instead. -->\n@AGENTS.md\n`;
  if (isRoot && claudeExtra) text += `\n${claudeExtra.replace(/^\n+/, '').replace(/\n*$/, '\n')}`;
  expected.set(isRoot ? 'CLAUDE.md' : `${dir}/CLAUDE.md`, { text });
}

// 2. .claude/rules from .agents/rules
const ruleFiles = exists(RULES_SRC)
  ? fs
      .readdirSync(abs(RULES_SRC))
      .filter((f) => f.endsWith('.md'))
      .sort()
  : [];
for (const file of ruleFiles) {
  const src = `${RULES_SRC}/${file}`;
  const { data, body } = parseFrontmatter(readText(src), src);
  let header;
  if (data.trigger === 'always_on') {
    header = '';
  } else if (data.trigger === 'glob') {
    const globs = parseGlobs(data.globs ?? data.glob, src);
    header = `---\npaths:\n${globs.map((g) => `  - ${JSON.stringify(g)}`).join('\n')}\n---\n`;
  } else {
    throw new Error(
      `${src}: \`trigger\` must be "always_on" or "glob" (got ${JSON.stringify(data.trigger ?? null)}). ` +
        'Put on-demand knowledge in a skill instead.',
    );
  }
  expected.set(`${CLAUDE_RULES}/${file}`, {
    text: `${header}<!-- ${MARKER} from ${src}. Do not edit. -->\n${body.replace(/^\n+/, '\n')}`,
  });
}

// 3. .claude/skills copied from .agents/skills (text normalised to LF, everything else byte-for-byte)
for (const src of walk(SKILLS_SRC)) {
  const target = `${CLAUDE_SKILLS}/${src.slice(SKILLS_SRC.length + 1)}`;
  expected.set(
    target,
    isText(src) ? { text: readText(src) } : { bytes: fs.readFileSync(abs(src)) },
  );
}

// 4. The manifest: every generated file. Only files listed in a previous manifest are deleted.
let previousManifest = [];
if (exists(MANIFEST)) {
  try {
    previousManifest = JSON.parse(readText(MANIFEST)).files ?? [];
  } catch (error) {
    throw new Error(`${MANIFEST}: invalid JSON (${error.message}); delete it and run agents:sync`);
  }
}
const generatedFiles = [...expected.keys()].sort();
expected.set(MANIFEST, {
  text: `${JSON.stringify({ generatedBy: 'scripts/sync-agent-config.mjs', files: generatedFiles }, null, 2)}\n`,
});

function isUpToDate(rel, entry) {
  if (!exists(rel)) return false;
  return 'text' in entry
    ? readText(rel) === entry.text
    : fs.readFileSync(abs(rel)).equals(entry.bytes);
}

for (const [rel, entry] of expected) {
  if (isUpToDate(rel, entry)) continue;
  const present = exists(rel);
  if (present && rel.endsWith('CLAUDE.md') && !readText(rel).includes(MARKER)) {
    problems.push(`${rel} exists and was not generated; move its content into AGENTS.md first`);
    continue;
  }
  if (CHECK) {
    problems.push(`${rel} is ${present ? 'out of date' : 'missing'}`);
  } else {
    fs.mkdirSync(path.dirname(abs(rel)), { recursive: true });
    fs.writeFileSync(abs(rel), 'text' in entry ? entry.text : entry.bytes);
    console.log(`wrote   ${rel}`);
  }
}

// Stale: generated by an earlier run (listed in the manifest) but no longer produced.
for (const rel of previousManifest) {
  if (expected.has(rel) || !exists(rel)) continue;
  if (rel.endsWith('CLAUDE.md') && !readText(rel).includes(MARKER)) {
    problems.push(
      `${rel} is listed as generated but was edited by hand; delete or move it yourself`,
    );
  } else if (CHECK) {
    problems.push(`${rel} is stale (its source was removed)`);
  } else {
    fs.rmSync(abs(rel));
    console.log(`removed ${rel}`);
  }
}

// Unexpected: files nobody generated. Reported, never deleted.
const known = new Set([...expected.keys(), ...previousManifest]);
const unexpected = [
  ...walk(CLAUDE_RULES),
  ...walk(CLAUDE_SKILLS),
  ...gitListFiles(['CLAUDE.md']).filter((f) => readText(f).includes(MARKER)),
].filter((rel) => !known.has(rel));
for (const rel of unexpected) {
  problems.push(
    `${rel} was not generated from .agents/; move it into .agents/ (or delete it yourself). ` +
      'The sync script never deletes files it did not create.',
  );
}

if (problems.length > 0) {
  console.error(problems.map((p) => `✗ ${p}`).join('\n'));
  if (CHECK) console.error('\nRun `pnpm agents:sync` and commit the result.');
  process.exit(1);
}
console.log(CHECK ? '✓ agent config is in sync' : '✓ agent config synced');
