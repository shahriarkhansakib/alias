#!/usr/bin/env node
/**
 * Generates tool-specific agent files from the canonical, tool-neutral sources.
 *
 * Sources (edit these):
 *   AGENTS.md files anywhere in the repo   -> read natively by most agents
 *   .agents/rules/*.md                     -> read natively by Antigravity
 *   .agents/skills/<name>/                 -> read natively by Antigravity (Agent Skills standard)
 *
 * Generated (never edit by hand):
 *   CLAUDE.md next to every AGENTS.md      -> `@AGENTS.md` import for Claude Code
 *   .claude/rules/*.md                     -> Claude Code rules (`paths:` frontmatter)
 *   .claude/skills/<name>/                 -> copy of each skill for Claude Code
 *
 * Usage:
 *   node scripts/sync-agent-config.mjs          write the generated files
 *   node scripts/sync-agent-config.mjs --check  exit 1 if generated files are out of date
 */
import { execFileSync } from 'node:child_process';
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const ROOT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const CHECK = process.argv.includes('--check');
const MARKER = 'Generated by scripts/sync-agent-config.mjs';
const RULES_SRC = '.agents/rules';
const SKILLS_SRC = '.agents/skills';
const CLAUDE_RULES = '.claude/rules';
const CLAUDE_SKILLS = '.claude/skills';

/** @type {Map<string, string>} repo-relative path -> expected content */
const expected = new Map();

function toPosix(p) {
  return p.split(path.sep).join('/');
}

function read(rel) {
  return fs.readFileSync(path.join(ROOT, rel), 'utf8').replace(/\r\n/g, '\n');
}

function listAgentsFiles() {
  const out = execFileSync(
    'git',
    ['ls-files', '--cached', '--others', '--exclude-standard', '--', 'AGENTS.md', '**/AGENTS.md'],
    { cwd: ROOT, encoding: 'utf8' },
  );
  return out
    .split('\n')
    .map((l) => l.trim())
    .filter((l) => l && !l.startsWith('.agents/'))
    .sort();
}

function parseFrontmatter(text, file) {
  const match = text.match(/^---\n([\s\S]*?)\n---\n?([\s\S]*)$/);
  if (!match) throw new Error(`${file}: missing YAML frontmatter`);
  const data = {};
  for (const line of match[1].split('\n')) {
    const kv = line.match(/^(\w+):\s*(.*)$/);
    if (!kv) continue;
    data[kv[1]] = kv[2].trim().replace(/^"(.*)"$/, '$1');
  }
  return { data, body: match[2] };
}

// 1. CLAUDE.md next to every AGENTS.md
for (const agentsFile of listAgentsFiles()) {
  const dir = path.posix.dirname(agentsFile);
  const target = dir === '.' ? 'CLAUDE.md' : `${dir}/CLAUDE.md`;
  const lines = [
    `<!-- ${MARKER} from AGENTS.md. Do not edit; edit AGENTS.md instead. -->`,
    '@AGENTS.md',
    '',
  ];
  if (dir === '.') {
    lines.push(
      '## Claude Code',
      '',
      '- Use plan mode for any change touching more than one file, and wait for approval.',
      '- Rules in `.claude/rules/` and skills in `.claude/skills/` are generated from `.agents/`.',
      '',
    );
  }
  expected.set(target, lines.join('\n'));
}

// 2. .claude/rules from .agents/rules
const ruleFiles = fs.existsSync(path.join(ROOT, RULES_SRC))
  ? fs
      .readdirSync(path.join(ROOT, RULES_SRC))
      .filter((f) => f.endsWith('.md'))
      .sort()
  : [];
for (const file of ruleFiles) {
  const src = `${RULES_SRC}/${file}`;
  const { data, body } = parseFrontmatter(read(src), src);
  const globs = data.globs ?? data.glob;
  let header;
  if (data.trigger === 'always_on') {
    header = '';
  } else if (data.trigger === 'glob' && globs) {
    const paths = globs
      .split(',')
      .map((g) => g.trim())
      .filter(Boolean)
      .map((g) => `  - "${g}"`);
    header = `---\npaths:\n${paths.join('\n')}\n---\n`;
  } else {
    throw new Error(
      `${src}: trigger must be "always_on" or "glob" (with globs). ` +
        'Put on-demand knowledge in a skill instead.',
    );
  }
  expected.set(
    `${CLAUDE_RULES}/${file}`,
    `${header}<!-- ${MARKER} from ${src}. Do not edit. -->\n${body.replace(/^\n+/, '\n')}`,
  );
}

// 3. .claude/skills copied from .agents/skills
function walk(relDir) {
  const abs = path.join(ROOT, relDir);
  if (!fs.existsSync(abs)) return [];
  return fs.readdirSync(abs, { withFileTypes: true }).flatMap((entry) => {
    const rel = `${relDir}/${entry.name}`;
    return entry.isDirectory() ? walk(rel) : [rel];
  });
}
for (const src of walk(SKILLS_SRC)) {
  expected.set(`${CLAUDE_SKILLS}/${src.slice(SKILLS_SRC.length + 1)}`, read(src));
}

// Stale generated files: anything in the generated folders that has no source any more.
const stale = [...walk(CLAUDE_RULES), ...walk(CLAUDE_SKILLS)].filter((f) => !expected.has(f));
const strayClaudeMd = execFileSync(
  'git',
  ['ls-files', '--cached', '--others', '--exclude-standard', '--', 'CLAUDE.md', '**/CLAUDE.md'],
  { cwd: ROOT, encoding: 'utf8' },
)
  .split('\n')
  .map((l) => l.trim())
  .filter((l) => l && !expected.has(l) && read(l).includes(MARKER));
stale.push(...strayClaudeMd);

const problems = [];
for (const [rel, content] of expected) {
  const abs = path.join(ROOT, rel);
  const current = fs.existsSync(abs) ? read(rel) : null;
  if (current === content) continue;
  if (current !== null && rel.endsWith('CLAUDE.md') && !current.includes(MARKER)) {
    problems.push(`${rel} exists and was not generated; move its content into AGENTS.md first`);
    continue;
  }
  if (CHECK) {
    problems.push(`${rel} is ${current === null ? 'missing' : 'out of date'}`);
  } else {
    fs.mkdirSync(path.dirname(abs), { recursive: true });
    fs.writeFileSync(abs, content);
    console.log(`wrote   ${toPosix(rel)}`);
  }
}
for (const rel of stale) {
  if (CHECK) {
    problems.push(`${rel} is stale (its source was removed)`);
  } else {
    fs.rmSync(path.join(ROOT, rel));
    console.log(`removed ${toPosix(rel)}`);
  }
}

if (problems.length > 0) {
  console.error(problems.map((p) => `✗ ${p}`).join('\n'));
  if (CHECK) console.error('\nRun `pnpm agents:sync` and commit the result.');
  process.exit(1);
}
console.log(CHECK ? '✓ agent config is in sync' : '✓ agent config synced');
