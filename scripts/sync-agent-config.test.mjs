// Tests for scripts/sync-agent-config.mjs. Each test builds a throwaway git repository in the OS
// temp folder, copies the script into it and runs it with Node, exactly as `pnpm agents:sync` does.
// Uses Vitest globals (see scripts/vitest.config.mjs).
import { execFileSync, spawnSync } from 'node:child_process';
import fs from 'node:fs';
import os from 'node:os';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const SCRIPT = path.join(path.dirname(fileURLToPath(import.meta.url)), 'sync-agent-config.mjs');
const BOM = '\uFEFF';
const BINARY = Buffer.from([
  0x89, 0x50, 0x4e, 0x47, 0x0d, 0x0a, 0x1a, 0x0a, 0x00, 0xff, 0xfe, 0x0d,
]);

let repo;

function write(rel, content) {
  const file = path.join(repo, rel);
  fs.mkdirSync(path.dirname(file), { recursive: true });
  fs.writeFileSync(file, content);
}

function read(rel) {
  return fs.readFileSync(path.join(repo, rel), 'utf8');
}

function has(rel) {
  return fs.existsSync(path.join(repo, rel));
}

function git(...args) {
  execFileSync('git', args, { cwd: repo, stdio: 'ignore' });
}

function sync(...args) {
  const result = spawnSync(process.execPath, ['scripts/sync-agent-config.mjs', ...args], {
    cwd: repo,
    encoding: 'utf8',
  });
  return { status: result.status, out: `${result.stdout}${result.stderr}` };
}

const check = () => sync('--check');

function globRule(globsLine) {
  return `---\ntrigger: glob\n${globsLine}\ndescription: "Test rule."\n---\n\n# Rule\n\n- Body.\n`;
}

beforeEach(() => {
  repo = fs.mkdtempSync(path.join(os.tmpdir(), 'agent-sync-'));
  git('init', '-q');
  git('config', 'core.autocrlf', 'false');
  write('scripts/sync-agent-config.mjs', fs.readFileSync(SCRIPT));
  write('AGENTS.md', '# Root\n');
  write('apps/api/AGENTS.md', '# API\n');
  write('.agents/claude-code.md', '## Claude Code\n\n- Plan first.\n');
  write('.agents/rules/web.md', globRule('globs: "apps/web/**, packages/ui/**"'));
  write('.agents/rules/security.md', '---\ntrigger: always_on\n---\n\n# Security\n');
  write('.agents/skills/demo/SKILL.md', '---\nname: demo\ndescription: Demo.\n---\n\n# Demo\n');
});

afterEach(() => {
  fs.rmSync(repo, { recursive: true, force: true });
});

describe('sync-agent-config', () => {
  describe('happy paths', () => {
    it('generates CLAUDE.md files, rules, skills and the manifest, then passes --check', () => {
      expect(sync().status).toBe(0);

      expect(read('CLAUDE.md')).toBe(
        '<!-- Generated by scripts/sync-agent-config.mjs from AGENTS.md and .agents/claude-code.md. ' +
          'Do not edit; edit the source instead. -->\n@AGENTS.md\n\n## Claude Code\n\n- Plan first.\n',
      );
      expect(read('apps/api/CLAUDE.md')).toContain('@AGENTS.md');
      expect(read('apps/api/CLAUDE.md')).not.toContain('Claude Code');
      expect(read('.claude/rules/web.md')).toMatch(
        /^---\npaths:\n {2}- "apps\/web\/\*\*"\n {2}- "packages\/ui\/\*\*"\n---\n/,
      );
      expect(read('.claude/rules/security.md')).toMatch(/^<!-- Generated/);
      expect(read('.claude/skills/demo/SKILL.md')).toBe(read('.agents/skills/demo/SKILL.md'));
      expect(JSON.parse(read('.claude/.generated-manifest.json')).files).toEqual([
        '.claude/rules/security.md',
        '.claude/rules/web.md',
        '.claude/skills/demo/SKILL.md',
        'CLAUDE.md',
        'apps/api/CLAUDE.md',
      ]);
      expect(check()).toEqual({ status: 0, out: expect.stringContaining('in sync') });
    });

    it('accepts globs as a YAML block list', () => {
      write('.agents/rules/web.md', globRule('globs:\n  - "apps/web/**"\n  - \'src/{a,b}/**\''));
      expect(sync().status).toBe(0);
      expect(read('.claude/rules/web.md')).toMatch(
        /^---\npaths:\n {2}- "apps\/web\/\*\*"\n {2}- "src\/\{a,b\}\/\*\*"\n---\n/,
      );
    });

    it('accepts globs as a YAML flow list', () => {
      write('.agents/rules/web.md', globRule('globs: ["apps/web/**", apps/api/**]'));
      expect(sync().status).toBe(0);
      expect(read('.claude/rules/web.md')).toContain('  - "apps/web/**"\n  - "apps/api/**"\n');
    });

    it('copies a binary skill asset byte for byte', () => {
      write('.agents/skills/demo/assets/logo.png', BINARY);
      expect(sync().status).toBe(0);
      expect(fs.readFileSync(path.join(repo, '.claude/skills/demo/assets/logo.png'))).toEqual(
        BINARY,
      );
      expect(check().status).toBe(0);
    });

    it('removes the empty folders of a deleted skill but keeps .claude/skills', () => {
      write('.agents/skills/other/SKILL.md', '---\nname: other\ndescription: Other.\n---\n');
      write('.agents/skills/demo/assets/img/logo.png', BINARY);
      sync();
      fs.rmSync(path.join(repo, '.agents/skills/demo'), { recursive: true });

      expect(sync().status).toBe(0);
      expect(has('.claude/skills/demo')).toBe(false);
      expect(has('.claude/skills/other/SKILL.md')).toBe(true);
      expect(check().status).toBe(0);
    });
  });

  describe('edge cases', () => {
    it('keeps a skill folder that still holds generated files', () => {
      write('.agents/skills/demo/assets/logo.png', BINARY);
      sync();
      fs.rmSync(path.join(repo, '.agents/skills/demo/assets'), { recursive: true });

      expect(sync().status).toBe(0);
      expect(has('.claude/skills/demo/assets')).toBe(false);
      expect(has('.claude/skills/demo/SKILL.md')).toBe(true);
    });

    it('never removes the .claude/rules or .claude/skills roots, even when empty', () => {
      sync();
      fs.rmSync(path.join(repo, '.agents/rules'), { recursive: true });
      fs.rmSync(path.join(repo, '.agents/skills'), { recursive: true });

      expect(sync().status).toBe(0);
      expect(fs.readdirSync(path.join(repo, '.claude/rules'))).toEqual([]);
      expect(fs.readdirSync(path.join(repo, '.claude/skills'))).toEqual([]);
    });

    it('strips a UTF-8 BOM from a source rule and skill', () => {
      write('.agents/rules/web.md', BOM + globRule('globs: "apps/web/**"'));
      write('.agents/skills/demo/SKILL.md', `${BOM}---\nname: demo\ndescription: Demo.\n---\n`);
      expect(sync().status).toBe(0);
      expect(read('.claude/rules/web.md').startsWith('---\npaths:')).toBe(true);
      expect(read('.claude/skills/demo/SKILL.md').startsWith('---\nname: demo')).toBe(true);
      expect(check().status).toBe(0);
    });

    it('reads CRLF sources and writes LF', () => {
      write('.agents/rules/web.md', globRule('globs: "apps/web/**"').replace(/\n/g, '\r\n'));
      write('.agents/skills/demo/SKILL.md', '---\r\nname: demo\r\ndescription: Demo.\r\n---\r\n');
      expect(sync().status).toBe(0);
      expect(read('.claude/rules/web.md')).not.toContain('\r');
      expect(read('.claude/skills/demo/SKILL.md')).not.toContain('\r');
      expect(check().status).toBe(0);
    });

    it('treats a generated file checked out with CRLF as up to date', () => {
      sync();
      write('.claude/rules/web.md', read('.claude/rules/web.md').replace(/\n/g, '\r\n'));
      expect(check().status).toBe(0);
    });

    it('does not touch CRLF bytes inside a binary asset', () => {
      write('.agents/skills/demo/data.bin', Buffer.from('a\r\nb\r\n'));
      sync();
      expect(fs.readFileSync(path.join(repo, '.claude/skills/demo/data.bin')).toString()).toBe(
        'a\r\nb\r\n',
      );
    });

    it('reports and then deletes a stale generated file listed in the manifest', () => {
      sync();
      fs.rmSync(path.join(repo, '.agents/rules/web.md'));

      expect(check()).toEqual({
        status: 1,
        out: expect.stringContaining('.claude/rules/web.md is stale'),
      });
      expect(sync().status).toBe(0);
      expect(has('.claude/rules/web.md')).toBe(false);
      expect(JSON.parse(read('.claude/.generated-manifest.json')).files).not.toContain(
        '.claude/rules/web.md',
      );
    });

    it('ignores an AGENTS.md that git still lists but is gone from disk', () => {
      sync();
      git('add', '-A');
      fs.rmSync(path.join(repo, 'apps/api/AGENTS.md'));

      expect(check()).toEqual({
        status: 1,
        out: expect.stringContaining('apps/api/CLAUDE.md is stale'),
      });
      expect(sync().status).toBe(0);
      expect(has('apps/api/CLAUDE.md')).toBe(false);
    });

    it('omits the Claude Code section when .agents/claude-code.md does not exist', () => {
      fs.rmSync(path.join(repo, '.agents/claude-code.md'));
      sync();
      expect(read('CLAUDE.md')).toBe(
        '<!-- Generated by scripts/sync-agent-config.mjs from AGENTS.md. ' +
          'Do not edit; edit the source instead. -->\n@AGENTS.md\n',
      );
    });
  });

  describe('error cases', () => {
    it('reports an unexpected hand-written file and never deletes it', () => {
      sync();
      write('.claude/rules/mine.md', '# Mine\n');
      write('.claude/skills/personal/SKILL.md', '# Personal\n');

      for (const run of [check, sync]) {
        const result = run();
        expect(result.status).toBe(1);
        expect(result.out).toContain('.claude/rules/mine.md was not generated');
        expect(result.out).toContain('.claude/skills/personal/SKILL.md was not generated');
      }
      expect(read('.claude/rules/mine.md')).toBe('# Mine\n');
      expect(has('.claude/skills/personal/SKILL.md')).toBe(true);
    });

    it('keeps a stale skill folder that holds a hand-written file', () => {
      sync();
      write('.claude/skills/demo/notes.md', '# Mine\n');
      fs.rmSync(path.join(repo, '.agents/skills/demo'), { recursive: true });

      const result = sync();
      expect(result.status).toBe(1);
      expect(result.out).toContain('.claude/skills/demo/notes.md was not generated');
      expect(has('.claude/skills/demo/SKILL.md')).toBe(false);
      expect(read('.claude/skills/demo/notes.md')).toBe('# Mine\n');
    });

    it('fails --check when a generated file was edited by hand', () => {
      sync();
      write('.claude/rules/web.md', `${read('.claude/rules/web.md')}- extra\n`);
      expect(check()).toEqual({
        status: 1,
        out: expect.stringContaining('.claude/rules/web.md is out of date'),
      });
    });

    it('fails --check when a generated file is missing', () => {
      sync();
      fs.rmSync(path.join(repo, '.claude/skills/demo/SKILL.md'));
      expect(check().out).toContain('.claude/skills/demo/SKILL.md is missing');
    });

    it('refuses to overwrite a hand-written CLAUDE.md next to an AGENTS.md', () => {
      write('apps/api/CLAUDE.md', '# My notes\n');
      const result = sync();
      expect(result.status).toBe(1);
      expect(result.out).toContain('apps/api/CLAUDE.md exists and was not generated');
      expect(read('apps/api/CLAUDE.md')).toBe('# My notes\n');
    });

    it('explains how to write globs when they are missing', () => {
      write('.agents/rules/web.md', globRule('globs:'));
      const result = sync();
      expect(result.status).toBe(1);
      expect(result.out).toContain('`trigger: glob` needs `globs`');
      expect(result.out).toContain('YAML list');
    });

    it('rejects an unknown trigger', () => {
      write('.agents/rules/web.md', '---\ntrigger: model_decision\n---\n# Rule\n');
      expect(sync().out).toContain(
        '`trigger` must be "always_on" or "glob" (got "model_decision")',
      );
    });

    it('rejects a rule without frontmatter', () => {
      write('.agents/rules/web.md', '# No frontmatter\n');
      expect(sync().out).toContain('.agents/rules/web.md: missing YAML frontmatter');
    });
  });
});
