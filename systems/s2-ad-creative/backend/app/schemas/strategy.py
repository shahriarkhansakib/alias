from enum import Enum
from typing import List, Optional, Dict, Any
from pydantic import BaseModel, Field, field_validator, ConfigDict
from app.templates.registry import is_template_registered


class CopyPolicyType(str, Enum):
    FACTUAL = "FACTUAL"
    USER_PROVIDED = "USER_PROVIDED"
    AI_GENERATED_CREATIVE = "AI_GENERATED_CREATIVE"


class PlacementDirection(str, Enum):
    LEFT = "left"
    RIGHT = "right"
    CENTER = "center"


class ConceptSpec(BaseModel):
    model_config = ConfigDict(extra="forbid")

    name: str = Field(..., min_length=1, max_length=150, description="Name or title of creative angle")
    creative_angle: str = Field(..., min_length=1, max_length=300, description="The psychological or stylistic hook")
    reasoning_notes: Optional[str] = Field(None, max_length=500, description="Strategic rationale for why this fits the brief")


class VisualDirectionSpec(BaseModel):
    model_config = ConfigDict(extra="forbid")

    mood: str = Field(..., min_length=1, max_length=150, description="Atmospheric tone (e.g. 'energetic, sleek dark mode')")
    lighting: str = Field(..., min_length=1, max_length=200, description="Lighting style (e.g. 'dramatic rim lighting with blue neon glow')")
    background_direction: str = Field(
        ...,
        min_length=10,
        max_length=500,
        description="Scenery description ONLY. Must describe visual environment with clean negative space and NO product or text.",
    )
    negative_prompt: str = Field(
        default="text, typography, watermark, logo, product, smartwatch, human, cluttered, blurry",
        max_length=300,
        description="Negative constraints explicitly preventing product or text generation in the background",
    )
    product_placement: PlacementDirection = Field(
        default=PlacementDirection.RIGHT,
        description="Canvas region allocated for the physical product cutout",
    )
    text_placement: PlacementDirection = Field(
        default=PlacementDirection.LEFT,
        description="Canvas region allocated for typography and offer messaging",
    )


class CopySpec(BaseModel):
    model_config = ConfigDict(extra="forbid")

    headline: str = Field(..., min_length=1, max_length=100, description="Primary advertisement headline")
    subheadline: str = Field(..., min_length=1, max_length=200, description="Supporting value proposition")
    cta: str = Field(..., min_length=1, max_length=35, description="Direct action button copy (e.g. 'Shop Now')")
    offer_mention: Optional[str] = Field(None, max_length=80, description="Specific price or discount text if highlighted")

    headline_policy: CopyPolicyType = Field(
        default=CopyPolicyType.AI_GENERATED_CREATIVE,
        description="Classification of headline origin",
    )
    subheadline_policy: CopyPolicyType = Field(
        default=CopyPolicyType.FACTUAL,
        description="Classification of subheadline origin",
    )
    cta_policy: CopyPolicyType = Field(
        default=CopyPolicyType.USER_PROVIDED,
        description="Classification of CTA origin",
    )


class CreativeStrategySpec(BaseModel):
    """
    Structured Creative Strategy generated by the LLM Art Director.
    Strictly specifies instructions for the rendering pipeline without drawing any pixels.
    """
    model_config = ConfigDict(extra="forbid")

    concept: ConceptSpec = Field(..., description="High-level creative concept")
    visual_direction: VisualDirectionSpec = Field(..., description="Lighting, mood, and empty scenery prompt")
    copy_spec: CopySpec = Field(..., description="Advertisement text hierarchy")
    template_id: str = Field(..., description="Predefined template identifier from registry")

    @field_validator("template_id")
    @classmethod
    def validate_registered_template(cls, v: str) -> str:
        if not is_template_registered(v):
            raise ValueError(
                f"Unknown template_id '{v}'. Template must be one of the registered templates: "
                "['product_sale_dark', 'product_launch', 'minimal_feature']"
            )
        return v


class ClaimAuditItem(BaseModel):
    model_config = ConfigDict(extra="forbid")

    text_segment: str
    classification: CopyPolicyType
    is_supported: bool
    source_reference: Optional[str] = None
    reason: Optional[str] = None


class ClaimValidationReport(BaseModel):
    model_config = ConfigDict(extra="forbid")

    passed: bool
    supported_facts: List[str] = Field(default_factory=list)
    creative_flourishes: List[str] = Field(default_factory=list)
    unsupported_claims: List[str] = Field(default_factory=list)
    price_check_passed: bool = True
    discount_check_passed: bool = True
    claims_audit: List[ClaimAuditItem] = Field(default_factory=list)
    summary: str


class StrategyGenerationResponse(BaseModel):
    model_config = ConfigDict(extra="forbid")

    status: str  # "APPROVED" or "REJECTED"
    strategy: Optional[CreativeStrategySpec] = None
    claim_report: ClaimValidationReport
    retry_count: int = 0
    strategy_id: Optional[str] = None
    job_id: Optional[str] = None
    created_at: Optional[str] = None

