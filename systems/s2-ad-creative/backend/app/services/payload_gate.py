from typing import Dict, Any, List
from pydantic import ValidationError

from app.schemas.brief import FinalAdBriefPayload
from app.schemas.validation import (
    BriefValidationResponse,
    ValidationReport,
    ValidationCheckItem,
    ValidationStatus,
    ValidationSeverity,
)


class PayloadGateService:
    """
    Validates the Final Ad Brief JSON payload against strict Pydantic v2 schemas.
    Halts structurally defective briefs before any external or expensive pipeline steps.
    """

    def validate_brief(self, payload: Dict[str, Any]) -> BriefValidationResponse:
        checks: List[ValidationCheckItem] = []
        errors: List[str] = []
        warnings: List[str] = []

        try:
            validated = FinalAdBriefPayload.model_validate(payload)
            checks.append(
                ValidationCheckItem(
                    code="PAYLOAD_SCHEMA_VALID",
                    message="Final Ad Brief schema validation passed with all required fields present.",
                    severity=ValidationSeverity.INFO,
                    passed=True,
                )
            )

            # Check for recommended optional fields
            if not validated.brand.logo_url:
                warn = "Brand logo URL is not supplied. A typography-only logo treatment will be required."
                checks.append(
                    ValidationCheckItem(
                        code="OPTIONAL_LOGO_MISSING",
                        message=warn,
                        severity=ValidationSeverity.WARNING,
                        passed=True,
                    )
                )
                warnings.append(warn)

            if not validated.brand.colors:
                warn = "Brand colors are not specified. Default high-contrast palette will be inferred."
                checks.append(
                    ValidationCheckItem(
                        code="OPTIONAL_BRAND_COLORS_MISSING",
                        message=warn,
                        severity=ValidationSeverity.WARNING,
                        passed=True,
                    )
                )
                warnings.append(warn)

            if not validated.ad_copy or not validated.ad_copy.cta:
                checks.append(
                    ValidationCheckItem(
                        code="COPY_CTA_INFERRED",
                        message="Call-To-Action (CTA) not explicitly supplied; will be generated by creative strategy.",
                        severity=ValidationSeverity.INFO,
                        passed=True,
                    )
                )

            # Check approved claims
            if not validated.approved_claims and not validated.product.features:
                warn = "No approved claims or product features specified. Creative strategy will have limited factual grounding."
                checks.append(
                    ValidationCheckItem(
                        code="MINIMAL_CLAIMS_WARNING",
                        message=warn,
                        severity=ValidationSeverity.WARNING,
                        passed=True,
                    )
                )
                warnings.append(warn)
            else:
                checks.append(
                    ValidationCheckItem(
                        code="APPROVED_CLAIMS_VERIFIED",
                        message=f"Verified {len(validated.approved_claims)} approved claims and {len(validated.product.features)} product features.",
                        severity=ValidationSeverity.INFO,
                        passed=True,
                        metadata={
                            "claims_count": len(validated.approved_claims),
                            "features_count": len(validated.product.features),
                        },
                    )
                )

            status = ValidationStatus.WARNING if warnings else ValidationStatus.PASS
            summary = (
                f"Payload Gate accepted brief with {len(warnings)} non-blocking recommendation(s)."
                if warnings
                else "Payload Gate passed. Brief structure is fully valid."
            )

            report = ValidationReport(
                status=status,
                gate_name="Payload Gate",
                summary=summary,
                checks=checks,
                errors=[],
                warnings=warnings,
            )

            return BriefValidationResponse(
                is_valid=True,
                status=status,
                report=report,
                validated_payload=validated.model_dump(mode="json"),
            )

        except ValidationError as ve:
            for err in ve.errors():
                loc = " -> ".join(str(l) for l in err.get("loc", []))
                msg = f"Field [{loc}]: {err.get('msg')}"
                errors.append(msg)
                checks.append(
                    ValidationCheckItem(
                        code="SCHEMA_FIELD_ERROR",
                        message=msg,
                        severity=ValidationSeverity.ERROR,
                        passed=False,
                        metadata={"loc": err.get("loc"), "type": err.get("type")},
                    )
                )

            report = ValidationReport(
                status=ValidationStatus.FAIL,
                gate_name="Payload Gate",
                summary=f"Payload Gate rejected brief with {len(errors)} structural validation error(s).",
                checks=checks,
                errors=errors,
                warnings=warnings,
            )

            return BriefValidationResponse(
                is_valid=False,
                status=ValidationStatus.FAIL,
                report=report,
                validated_payload=None,
            )


payload_gate_service = PayloadGateService()
